const solarArchive = process.env.CTTN_SOLAR_TGZ;
const loomArchive = process.env.CTTN_LOOM_TGZ;
if (!solarArchive || !loomArchive) throw new Error("Set CTTN_SOLAR_TGZ and CTTN_LOOM_TGZ to the qualified Solar Sail and Stellar Loom archives");

const catalogSource = readFileSync(join(sourceRoot, "appearance-catalog/catalog.json"), "utf8");
const catalog = JSON.parse(catalogSource);
const declaredEngines = JSON.parse(readFileSync(join(sourceRoot, "engines.json"), "utf8"));
const templateSource = readFileSync(join(sourceRoot, "sttn/v0.4/terminal-nova.theme.json"), "utf8");
const profiles = catalog.profiles.map(profile => ({
  id: profile.id,
  sourcePath: profile.source,
  label: profile.label,
  review: profile.review,
  source: readFileSync(resolve(sourceRoot, "appearance-catalog", profile.source), "utf8"),
}));
const inputs = { catalog, catalogSource, declaredEngines, templateSource, profiles };
let engines;

function resolvedRole(theme, variant, mode, role) {
  const variantRecord = theme.accentVariants[variant];
  return theme.tokenSets[variantRecord.tokenSet][variantRecord[mode][role]];
}

before(async () => { engines = await loadEngines({ solar: solarArchive, loom: loomArchive }); });
after(() => engines && rmSync(engines.work, { recursive: true, force: true }));

test("pure compilation is deterministic and preserves the application layer", () => {
  const first = compileAppearanceCollection(engines, inputs);
  const second = compileAppearanceCollection(engines, inputs);
  assert.deepEqual([...first.files.keys()], [...second.files.keys()]);
  for (const [path, content] of first.files) assert.equal(content, second.files.get(path), path);
  assert.equal(first.inventory.digest, second.inventory.digest);
  assert.equal(first.files.size, 93);
  assert.equal(first.inventory.members.length, 92);
  assert.equal(first.inventory.members.some(member => member.path === "inventory.json"), false);
  assert.deepEqual(first.inventory, JSON.parse(first.files.get("inventory.json")));
  assert.match(first.files.get("terminal-nova/application.css"), /@layer theme-forge-application-baseline/);
  assert.match(first.files.get("terminal-nova/application.css"), /^\/\* Generated by Theme Forge Solar Sail — Tailwind CSS v4 & shadcn\/ui application theme \*\/\n@custom-variant dark/);
  assert.ok(first.files.get("terminal-nova/application.css").indexOf("@theme inline") < first.files.get("terminal-nova/application.css").indexOf("@layer theme-forge-application-baseline"));
  assert.match(first.files.get("nebular/appearance-extensions.css"), /color-scheme: dark/);
  const ids = ["terminal-nova", "nebular", "developer", "graphic-designer", "anime", "gamer"];
  assert.deepEqual(first.catalog.families.map(family => family.id), ids);
  for (const id of ids) {
    for (const path of [`${id}/cttn.css`, `${id}/application.css`]) {
      assert.match(first.files.get(path), /:root/);
      assert.match(first.files.get(path), /:root\[data-theme='dark'\]/);
    }
    assert.match(first.files.get(`${id}/sttn.css`), /:root/);
    assert.match(first.files.get(`${id}/sttn.css`), /:root\[data-theme='light'\]/);
    const family = first.catalog.families.find(candidate => candidate.id === id);
    assert.ok(family.targetDisposition.solar.length > 0);
    assert.ok(family.targetDisposition.loom.length > 0);
    assert.equal(family.targetDisposition.codePresentation, "Existing STTN code presentation retained; the separately returned syntax model is not silently substituted");
    assert.deepEqual(family.targetDisposition.loomVariants.retainedLegacy, ["cyan", "orange"]);
    assert.ok(family.targetDisposition.profileDerivedRoles.length > 0);
    assert.ok(family.targetDisposition.templateRetainedRoles.length > 0);
    assert.equal(family.targetDisposition.roleComparison.method, "resolved-value-comparison-to-declared-template");
    assert.equal(family.targetDisposition.roleComparison.causalProvenance, false);
    assert.ok(family.targetDisposition.loomNotApplied.length > 0);
    assert.equal(family.targetDisposition.hoistDisposition.status, "hoisted");
    assert.equal(family.targetDisposition.authoredSyntax.applied, false);
    if (["developer", "graphic-designer", "anime", "gamer"].includes(id)) {
      assert.equal(family.targetDisposition.authoredSyntax.status, "unsupported");
      assert.equal(family.targetDisposition.authoredSyntax.sourcePath, "code.syntax");
    }
  }
  assert.equal(first.catalog.sourceIdentity.catalog.sha256, sha256(catalogSource));
  assert.equal(first.catalog.sourceIdentity.pathBase, "repository-root");
  assert.deepEqual(first.catalog.sourceIdentity.profiles.map(profile => profile.id), ids);
  assert.deepEqual(first.catalog.sourceIdentity.engines.map(engine => engine.integrity), declaredEngines.engines.map(engine => engine.integrity));

  const gamerCatalog = JSON.parse(first.files.get("gamer/sttn.catalog.json"));
  const gamerTokens = gamerCatalog.tokenSets[gamerCatalog.accentVariants.orange.tokenSet];
  assert.equal(gamerTokens[gamerCatalog.accentVariants.orange.light["accent-base"]], "#81284e");
  assert.notEqual(gamerTokens[gamerCatalog.accentVariants.cyan.light["accent-base"]], "#81284e");
  const template = JSON.parse(templateSource);
  assert.equal(resolvedRole(gamerCatalog, "cyan", "light", "page"), "#c8d9d8");
  const nebularCatalog = JSON.parse(first.files.get("nebular/sttn.catalog.json"));
  assert.equal(resolvedRole(nebularCatalog, "gold", "light", "page"), "#ded4e9");
  const animeCatalog = JSON.parse(first.files.get("anime/sttn.catalog.json"));
  assert.equal(resolvedRole(animeCatalog, "rose", "light", "page"), "#e8d2e2");
  assert.equal(resolvedRole(animeCatalog, "purple", "light", "accent-base"), "#543770");
  assert.notEqual(resolvedRole(animeCatalog, "purple", "light", "accent-base"), resolvedRole(template, "cyan", "light", "accent-base"));
  const gamerReport = first.catalog.families.find(family => family.id === "gamer");
  assert.ok(gamerReport.targetDisposition.loomNotApplied.some(entry => entry.kind === "report-default" && entry.targetPath === "tabs.activeIndicator"));
  assert.ok(gamerReport.targetDisposition.loomNotApplied.some(entry => entry.targetPath === "frame" || entry.sourcePath?.startsWith("code.")));
  assert.ok(gamerReport.targetDisposition.loomNotApplied.some(entry => entry.sourcePath?.startsWith("code.syntax.")));
  assert.ok(gamerReport.targetDisposition.loomNotApplied.some(entry => entry.targetPath?.split(";").some(path => path.startsWith("chrome."))));
});

